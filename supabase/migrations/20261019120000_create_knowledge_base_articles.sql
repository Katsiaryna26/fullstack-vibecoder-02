BEGIN;

CREATE TABLE public.knowledge_base_articles (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title text NOT NULL,
    content text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT knowledge_base_articles_pkey PRIMARY KEY (id)
);

CREATE OR REPLACE FUNCTION public.set_knowledge_base_article_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER set_knowledge_base_article_updated_at
BEFORE UPDATE ON public.knowledge_base_articles
FOR EACH ROW
EXECUTE FUNCTION public.set_knowledge_base_article_updated_at();

COMMIT;
