create table public.clients (
                                id bigint generated by default as identity not null,
                                created_at timestamp with time zone not null default now(),
                                user_telegram_id character varying null,
                                first_name character varying null,
                                last_name character varying null,
                                last_message_at timestamp without time zone not null,
                                constraint Clients_pkey primary key (id)
) TABLESPACE pg_default;

CREATE UNIQUE INDEX IF NOT EXISTS clients_user_telegram_id_uidx
    ON public.clients (user_telegram_id);

create table public.messages (
                                 id bigint generated by default as identity not null,
                                 created_at timestamp with time zone not null default now(),
                                 author character varying null,
                                 body text null,
                                 messenger_user_id character varying null,
                                 messenger_type character varying null,
                                 client_id bigint null,
                                 constraint messages_pkey primary key (id),
                                 constraint messages_client_id_fkey foreign KEY (client_id) references clients (id)
) TABLESPACE pg_default;
